Create a clean and professional web dashboard UI for a government internal system called 
“Sistema de Validación de Solicitudes de Educadores Comunitarios”.

The main screen is a "Gestión de Solicitudes" dashboard used by government staff who validate 
applications from community educator candidates.

USER CONTEXT
The main user is a 45-year-old government validator with moderate digital skills. 
The interface must reduce cognitive load, avoid confusing icons, and support a simple linear workflow:
List → Select request → Review → Decide.

DESIGN STYLE
Follow the Mexican Government visual identity style:
- Minimalist interface
- High contrast
- Generous white space
- Primary color: institutional maroon (guinda)
- Secondary accents: gold and neutral gray
- Clean typography similar to Montserrat or Open Sans
- Accessible layout for users with low digital affinity

LAYOUT STRUCTURE

HEADER
- White background
- Government logo on the top left
- Page title: "Gestión de Solicitudes"
- User profile on the right with name "Roberto García"
- Simple clean navigation

STATUS SUMMARY CARDS (top dashboard section)
Show 5 horizontal cards with large numbers:
- En espera (light gray border, maroon number)
- Notificadas (blue border)
- Validadas (dark green border)
- Aceptadas (gold border)
- Rechazadas (dark gray border)

Cards should be clickable and act as quick filters.

FILTER SECTION
Below the cards create a filter container with:
- Input: Folio
- Input: Nombre
- Input: CURP
- Dropdown: Estatus
- Primary button: "Buscar"

Button style:
- Background: maroon
- White text
- Slight rounded corners

REQUEST TABLE
Clean and spacious table with good padding.

Columns:
- Folio
- Nombre del Aspirante
- CURP
- Estatus (with subtle colored label)
- Fecha de última acción
- Acción

For the action column use ONLY ONE clear action:
Text button: "Revisar detalle"

Avoid multiple icons.

VISUAL PRINCIPLES
- Large spacing between rows for readability
- Clear hierarchy
- Table headers highlighted in maroon
- Status tags with subtle colors
- Minimal icon usage
- Design optimized for clarity and efficiency

The design should feel like a modern government administrative dashboard focused on usability and clarity.